from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas

from app.models.job import Job
from app.services.storage import build_processed_asset_path, resolve_processed_asset_path


PAGE_WIDTH, PAGE_HEIGHT = A4
MARGIN = 40
CONTENT_WIDTH = PAGE_WIDTH - 2 * MARGIN
BOTTOM_LIMIT = 70

BRAND_DARK = colors.HexColor("#0F172A")
BRAND_ACCENT = colors.HexColor("#2563EB")
BRAND_ACCENT_LIGHT = colors.HexColor("#DBEAFE")
TEXT_BODY = colors.HexColor("#334155")
TEXT_MUTED = colors.HexColor("#94A3B8")
CARD_BG = colors.HexColor("#F8FAFC")
CARD_BORDER = colors.HexColor("#E2E8F0")

BODY_FONT = "Helvetica"
BOLD_FONT = "Helvetica-Bold"
BODY_SIZE = 9.5
LINE_HEIGHT = 13


def generate_job_pdf(
    job: Job,
    key_points: list[dict],
    analysis: dict[str, Any] | None = None,
    include_frames: bool = True,
) -> str:
    """Render the full Pro report from the persisted detailed-analysis payload."""
    asset_key = f"frames/{job.id}/report.pdf"
    pdf_path = build_processed_asset_path(asset_key)
    pdf_path.parent.mkdir(parents=True, exist_ok=True)
    doc = _DetailedReport(canvas.Canvas(str(pdf_path), pagesize=A4), job, include_frames)
    doc.draw_first_header()

    analysis = analysis or {}
    timeline = analysis.get("timeline") or []
    questions = analysis.get("questions_and_answers") or []
    participants = analysis.get("participants") or {}
    headlines = analysis.get("headlines") or []
    decisions = analysis.get("decisions") or []
    action_items = analysis.get("action_items") or []
    terms = analysis.get("terms") or []

    doc.quick_facts([
        ("How long", _duration_label(analysis.get("duration_seconds"))),
        ("People in the video", str(participants.get("count") or "Not detected")),
        ("Parts covered", str(len(timeline) or len(key_points))),
        ("Questions answered", str(len(questions))),
    ])
    doc.section("Summary")
    doc.paragraph(job.summary)

    overview = str(analysis.get("overview") or "").strip()
    if overview and _normalized(overview) != _normalized(job.summary):
        doc.section("What this video is about")
        doc.paragraph(overview)
    if headlines:
        doc.sub_heading("The main things to know")
        doc.bullets([_item_text(item) for item in headlines])

    names = participants.get("names") or []
    if names:
        doc.section("Who was in the video")
        doc.note(f"Names read from: {participants.get('source', 'the recording')}.")
        doc.name_grid([str(name) for name in names])

    doc.section("What happened, step by step")
    if timeline:
        for index, part in enumerate(timeline, start=1):
            doc.timeline(index, part)
    else:
        for index, point in enumerate(key_points, start=1):
            doc.timeline(index, {
                "title": point.get("title"),
                "start_seconds": point.get("timestamp_seconds"),
                "end_seconds": point.get("timestamp_seconds"),
                "bullets": [point.get("description") or ""],
                "frame_image_url": point.get("frame_image_url"),
            })

    if questions:
        doc.section("Questions people asked")
        for item in questions:
            doc.qa(item)
    if decisions:
        doc.section("Rules and decisions shared")
        doc.bullets([_item_text(item) for item in decisions])
    if action_items:
        doc.section("What to do next")
        doc.bullets([_item_text(item) for item in action_items])
    if terms:
        doc.section("Words explained in simple English")
        doc.bullets([f"{term.get('term')}: {term.get('meaning')}" for term in terms])

    doc.save()
    return asset_key


def generate_job_summary_pdf(job: Job, key_points: list[dict], include_frames: bool = True) -> str:
    """Render the shorter summary-only report used by the lightweight pipeline."""
    return _render_summary_pdf(
        job=job,
        key_points=key_points,
        asset_key=f"frames/{job.id}/summary-report.pdf",
        include_frames=include_frames,
    )


def _render_summary_pdf(
    job: Job,
    key_points: list[dict],
    asset_key: str,
    include_frames: bool,
) -> str:
    pdf_path = build_processed_asset_path(asset_key)
    pdf_path.parent.mkdir(parents=True, exist_ok=True)

    c = canvas.Canvas(str(pdf_path), pagesize=A4)
    page_state = {"number": 1}

    def draw_footer() -> None:
        c.setStrokeColor(CARD_BORDER)
        c.setLineWidth(0.5)
        c.line(MARGIN, 34, PAGE_WIDTH - MARGIN, 34)
        c.setFont("Helvetica", 8)
        c.setFillColor(TEXT_MUTED)
        c.drawString(MARGIN, 22, "Generated by FrameNote")
        c.drawRightString(PAGE_WIDTH - MARGIN, 22, f"Page {page_state['number']}")

    def draw_header(first_page: bool) -> float:
        band_height = 92 if first_page else 46
        c.setFillColor(BRAND_DARK)
        c.rect(0, PAGE_HEIGHT - band_height, PAGE_WIDTH, band_height, fill=1, stroke=0)
        if first_page:
            c.setFillColor(colors.white)
            c.setFont("Helvetica-Bold", 20)
            c.drawString(MARGIN, PAGE_HEIGHT - 42, "FrameNote Video Summary")
            c.setFont("Helvetica", 9)
            c.setFillColor(colors.HexColor("#CBD5E1"))
            source_label = job.source_url or job.file_name or "Uploaded media"
            c.drawString(MARGIN, PAGE_HEIGHT - 60, f"Job ID: {job.id}")
            c.drawString(MARGIN, PAGE_HEIGHT - 74, f"Source: {source_label[:90]}")
        else:
            c.setFillColor(colors.white)
            c.setFont("Helvetica-Bold", 11)
            c.drawString(MARGIN, PAGE_HEIGHT - 29, "FrameNote Video Summary (continued)")
        return PAGE_HEIGHT - band_height - 26

    def new_page() -> float:
        draw_footer()
        c.showPage()
        page_state["number"] += 1
        return draw_header(first_page=False)

    def draw_section_header(text: str, y: float) -> float:
        c.setFillColor(BRAND_ACCENT)
        c.rect(MARGIN, y - 3, 4, 14, fill=1, stroke=0)
        c.setFillColor(BRAND_DARK)
        c.setFont("Helvetica-Bold", 13)
        c.drawString(MARGIN + 10, y, text)
        return y - 22

    y = draw_header(first_page=True)
    y = draw_section_header("Summary", y)

    c.setFont("Helvetica", 10)
    c.setFillColor(TEXT_BODY)
    for line in _wrap_text(job.summary, 100):
        if y < 70:
            y = new_page()
            c.setFont("Helvetica", 10)
            c.setFillColor(TEXT_BODY)
        c.drawString(MARGIN, y, line)
        y -= 13

    y -= 14
    if y < 110:
        y = new_page()
    y = draw_section_header("Key Points", y)

    for idx, point in enumerate(key_points, start=1):
        y = _draw_key_point_card(
            c,
            idx=idx,
            point=point,
            y=y,
            new_page=new_page,
            include_frames=include_frames,
        )

    draw_footer()
    c.save()
    return asset_key


def _draw_key_point_card(
    c: canvas.Canvas,
    idx: int,
    point: dict,
    y: float,
    new_page,
    include_frames: bool,
) -> float:
    title = str(point.get("title") or "Key point")
    timestamp_label = _format_timestamp(point.get("timestamp_seconds", 0))
    description_lines = _wrap_text(str(point.get("description", "")), 95)

    frame_url = point.get("frame_image_url")
    frame_path: Path | None = None
    if include_frames and isinstance(frame_url, str) and "/assets/" in frame_url:
        try:
            frame_path = resolve_processed_asset_path(frame_url.split("/assets/", 1)[1])
        except Exception:
            frame_path = None

    line_height = 12.5
    header_row_height = 18
    image_width = CONTENT_WIDTH - 32
    image_height = image_width * 9 / 16 if frame_path else 0
    card_height = (
        16  # top padding
        + header_row_height
        + 8  # divider gap
        + len(description_lines) * line_height
        + (image_height + 10 if frame_path else 0)
        + 14  # bottom padding
    )

    if y - card_height < 70:
        y = new_page()

    card_top = y
    card_bottom = y - card_height

    c.setLineWidth(0.75)
    c.setFillColor(CARD_BG)
    c.setStrokeColor(CARD_BORDER)
    c.roundRect(MARGIN, card_bottom, CONTENT_WIDTH, card_height, 6, fill=1, stroke=1)

    text_x = MARGIN + 14
    row_y = card_top - 16 - 10

    c.setFont("Helvetica-Bold", 11)
    c.setFillColor(BRAND_DARK)
    c.drawString(text_x, row_y, f"{idx}. {title}")

    badge_width = c.stringWidth(timestamp_label, "Helvetica-Bold", 8) + 14
    badge_x = MARGIN + CONTENT_WIDTH - 14 - badge_width
    c.setFillColor(BRAND_ACCENT_LIGHT)
    c.roundRect(badge_x, row_y - 3, badge_width, 14, 7, fill=1, stroke=0)
    c.setFillColor(BRAND_ACCENT)
    c.setFont("Helvetica-Bold", 8)
    c.drawCentredString(badge_x + badge_width / 2, row_y + 1, timestamp_label)

    text_y = row_y - 8 - line_height
    c.setFont("Helvetica", 9.5)
    c.setFillColor(TEXT_BODY)
    for line in description_lines:
        c.drawString(text_x, text_y, line)
        text_y -= line_height

    if frame_path:
        image_y = text_y - image_height
        try:
            image = ImageReader(str(frame_path))
            c.drawImage(image, text_x, image_y, width=image_width, height=image_height, preserveAspectRatio=True)
        except Exception:
            pass

    return card_bottom - 16


def _format_timestamp(seconds: object) -> str:
    total_seconds = max(0, int(seconds or 0))
    minutes, secs = divmod(total_seconds, 60)
    return f"{minutes}:{secs:02d}"


def _wrap_text(text: str, max_chars: int) -> list[str]:
    words = text.split()
    if not words:
        return [""]


    lines: list[str] = []
    current = words[0]
    for word in words[1:]:
        candidate = f"{current} {word}"
        if len(candidate) <= max_chars:
            current = candidate
        else:
            lines.append(current)
            current = word
    lines.append(current)
    return lines


class _DetailedReport:
    def __init__(self, c: canvas.Canvas, job: Job, include_frames: bool) -> None:
        self.c = c
        self.job = job
        self.include_frames = include_frames
        self.page_number = 1
        self.y = PAGE_HEIGHT

    def draw_first_header(self) -> None:
        self.c.setFillColor(BRAND_DARK)
        self.c.rect(0, PAGE_HEIGHT - 92, PAGE_WIDTH, 92, fill=1, stroke=0)
        self.c.setFillColor(colors.white)
        self.c.setFont(BOLD_FONT, 20)
        self.c.drawString(MARGIN, PAGE_HEIGHT - 42, "FrameNote Video Report")
        self.c.setFont(BODY_FONT, 9)
        self.c.setFillColor(colors.HexColor("#CBD5E1"))
        source = self.job.source_url or self.job.file_name or "Uploaded media"
        self.c.drawString(MARGIN, PAGE_HEIGHT - 60, f"Job ID: {self.job.id}")
        self.c.drawString(MARGIN, PAGE_HEIGHT - 74, f"Source: {source[:90]}")
        self.y = PAGE_HEIGHT - 118

    def _footer(self) -> None:
        self.c.setStrokeColor(CARD_BORDER)
        self.c.setLineWidth(0.5)
        self.c.line(MARGIN, 34, PAGE_WIDTH - MARGIN, 34)
        self.c.setFont(BODY_FONT, 8)
        self.c.setFillColor(TEXT_MUTED)
        self.c.drawString(MARGIN, 22, "Generated by FrameNote")
        self.c.drawRightString(PAGE_WIDTH - MARGIN, 22, f"Page {self.page_number}")

    def new_page(self) -> None:
        self._footer()
        self.c.showPage()
        self.page_number += 1
        self.c.setFillColor(BRAND_DARK)
        self.c.rect(0, PAGE_HEIGHT - 46, PAGE_WIDTH, 46, fill=1, stroke=0)
        self.c.setFillColor(colors.white)
        self.c.setFont(BOLD_FONT, 11)
        self.c.drawString(MARGIN, PAGE_HEIGHT - 29, "FrameNote Video Report (continued)")
        self.y = PAGE_HEIGHT - 72

    def ensure(self, needed: float) -> None:
        if self.y - needed < BOTTOM_LIMIT:
            self.new_page()

    def save(self) -> None:
        self._footer()
        self.c.save()

    def section(self, title: str) -> None:
        self.ensure(48)
        self.y -= 12
        self.c.setFillColor(BRAND_ACCENT)
        self.c.rect(MARGIN, self.y - 3, 4, 14, fill=1, stroke=0)
        self.c.setFillColor(BRAND_DARK)
        self.c.setFont(BOLD_FONT, 13)
        self.c.drawString(MARGIN + 10, self.y, title)
        self.y -= 22

    def sub_heading(self, title: str) -> None:
        self.ensure(24)
        self.y -= 4
        self.c.setFillColor(BRAND_DARK)
        self.c.setFont(BOLD_FONT, 10)
        self.c.drawString(MARGIN, self.y, title)
        self.y -= 16

    def note(self, text: str) -> None:
        self.ensure(18)
        self.c.setFillColor(TEXT_MUTED)
        self.c.setFont(BODY_FONT, 8.5)
        self.c.drawString(MARGIN, self.y, text)
        self.y -= 15

    def paragraph(self, text: str) -> None:
        for block in _short_paragraphs(text):
            for line in _wrap_width(block, BODY_FONT, BODY_SIZE, CONTENT_WIDTH):
                self.ensure(LINE_HEIGHT)
                self.c.setFont(BODY_FONT, BODY_SIZE)
                self.c.setFillColor(TEXT_BODY)
                self.c.drawString(MARGIN, self.y, line)
                self.y -= LINE_HEIGHT
            self.y -= 5

    def bullets(self, items: list[str], x: float = MARGIN, width: float = CONTENT_WIDTH) -> None:
        for item in items:
            lines = _wrap_width(item, BODY_FONT, BODY_SIZE, width - 12)
            self.ensure(min(len(lines), 3) * LINE_HEIGHT)
            self.c.setFillColor(BRAND_ACCENT)
            self.c.circle(x + 4, self.y + 3.2, 1.8, fill=1, stroke=0)
            for line in lines:
                self.ensure(LINE_HEIGHT)
                self.c.setFont(BODY_FONT, BODY_SIZE)
                self.c.setFillColor(TEXT_BODY)
                self.c.drawString(x + 12, self.y, line)
                self.y -= LINE_HEIGHT
            self.y -= 3

    def quick_facts(self, facts: list[tuple[str, str]]) -> None:
        self.ensure(68)
        self.y -= 6
        top = self.y
        bottom = top - 52
        self.c.setFillColor(CARD_BG)
        self.c.setStrokeColor(CARD_BORDER)
        self.c.roundRect(MARGIN, bottom, CONTENT_WIDTH, 52, 6, fill=1, stroke=1)
        column_width = CONTENT_WIDTH / len(facts)
        for index, (label, value) in enumerate(facts):
            center = MARGIN + column_width * index + column_width / 2
            self.c.setFont(BODY_FONT, 8)
            self.c.setFillColor(TEXT_MUTED)
            self.c.drawCentredString(center, top - 20, label.upper())
            self.c.setFont(BOLD_FONT, 13)
            self.c.setFillColor(BRAND_DARK)
            self.c.drawCentredString(center, top - 38, value)
        self.y = bottom - 10

    def name_grid(self, names: list[str]) -> None:
        column_width = CONTENT_WIDTH / 3
        for row in range((len(names) + 2) // 3):
            self.ensure(15)
            for column in range(3):
                index = row * 3 + column
                if index >= len(names):
                    break
                x = MARGIN + column * column_width
                self.c.setFillColor(BRAND_ACCENT)
                self.c.circle(x + 4, self.y + 3.2, 1.8, fill=1, stroke=0)
                self.c.setFillColor(TEXT_BODY)
                self.c.setFont(BODY_FONT, BODY_SIZE)
                self.c.drawString(x + 12, self.y, _truncate_width(names[index], BODY_FONT, BODY_SIZE, column_width - 18))
            self.y -= 15
        self.y -= 6

    def timeline(self, index: int, part: dict[str, Any]) -> None:
        title = str(part.get("title") or "Part of the video")
        time_label = _time_range(part.get("start_seconds"), part.get("end_seconds"))
        bullets = [_item_text(item) for item in (part.get("bullets") or []) if _item_text(item).strip()]
        frame_path = _frame_path(part.get("frame_image_url")) if self.include_frames else None
        image_width = CONTENT_WIDTH - 28
        image_height = image_width * 9 / 16 if frame_path else 0
        line_count = sum(len(_wrap_width(item, BODY_FONT, BODY_SIZE, CONTENT_WIDTH - 40)) for item in bullets)
        self.ensure(min(34 + line_count * LINE_HEIGHT + image_height + 20, PAGE_HEIGHT - 160))
        self.y -= 4
        top = self.y
        self.c.setFont(BOLD_FONT, 11)
        self.c.setFillColor(BRAND_DARK)
        self.c.drawString(MARGIN + 14, top - 16, _truncate_width(f"{index}. {title}", BOLD_FONT, 11, CONTENT_WIDTH - 120))
        self._badge(time_label, top - 16)
        self.y = top - 34
        self.bullets(bullets, MARGIN + 14, CONTENT_WIDTH - 28)
        if frame_path:
            self.ensure(image_height + 12)
            self.y -= 4
            try:
                self.c.drawImage(ImageReader(str(frame_path)), MARGIN + 14, self.y - image_height, width=image_width, height=image_height, preserveAspectRatio=True, anchor="n")
                self.y -= image_height + 6
            except Exception:
                pass
        self._divider()

    def qa(self, item: dict[str, Any]) -> None:
        question = str(item.get("question") or "").strip()
        answer = str(item.get("answer") or "").strip()
        asked_by = str(item.get("asked_by") or "A participant").strip()
        lines = _wrap_width(f"Q: {question}", BOLD_FONT, BODY_SIZE, CONTENT_WIDTH - 150)
        self.ensure(len(lines) * LINE_HEIGHT + 34)
        top = self.y
        for line in lines:
            self.c.setFont(BOLD_FONT, BODY_SIZE)
            self.c.setFillColor(BRAND_DARK)
            self.c.drawString(MARGIN + 14, self.y, line)
            self.y -= LINE_HEIGHT
        self._badge(f"{asked_by[:20]} | {_clock(item.get('time_seconds'))}", top)
        self.y -= 2
        for line in _wrap_width(f"A: {answer}", BODY_FONT, BODY_SIZE, CONTENT_WIDTH - 28):
            self.ensure(LINE_HEIGHT)
            self.c.setFont(BODY_FONT, BODY_SIZE)
            self.c.setFillColor(TEXT_BODY)
            self.c.drawString(MARGIN + 14, self.y, line)
            self.y -= LINE_HEIGHT
        self._divider()

    def _badge(self, label: str, y: float) -> None:
        width = stringWidth(label, BOLD_FONT, 8) + 14
        x = MARGIN + CONTENT_WIDTH - width
        self.c.setFillColor(BRAND_ACCENT_LIGHT)
        self.c.roundRect(x, y - 3, width, 14, 7, fill=1, stroke=0)
        self.c.setFillColor(BRAND_ACCENT)
        self.c.setFont(BOLD_FONT, 8)
        self.c.drawCentredString(x + width / 2, y + 1, label)

    def _divider(self) -> None:
        self.c.setStrokeColor(CARD_BORDER)
        self.c.setLineWidth(0.5)
        self.c.line(MARGIN, self.y - 2, PAGE_WIDTH - MARGIN, self.y - 2)
        self.y -= 14


def _item_text(item: Any) -> str:
    if isinstance(item, dict):
        return str(item.get("title") or item.get("text") or item)
    return str(item)


def _normalized(text: str) -> str:
    return " ".join(str(text or "").lower().split())


def _short_paragraphs(text: str) -> list[str]:
    cleaned = " ".join(str(text or "").split())
    if not cleaned:
        return [""]
    sentences: list[str] = []
    current = ""
    for char in cleaned:
        current += char
        if char in ".!?" and len(current.strip()) > 2:
            sentences.append(current.strip())
            current = ""
    if current.strip():
        sentences.append(current.strip())
    return [" ".join(sentences[index:index + 2]) for index in range(0, len(sentences), 2)]


def _wrap_width(text: str, font: str, size: float, max_width: float) -> list[str]:
    words = " ".join(str(text or "").split()).split(" ")
    if not words or words == [""]:
        return [""]
    lines: list[str] = []
    current = words[0]
    for word in words[1:]:
        candidate = f"{current} {word}"
        if stringWidth(candidate, font, size) <= max_width:
            current = candidate
        else:
            lines.append(current)
            current = word
    lines.append(current)
    return lines


def _truncate_width(text: str, font: str, size: float, max_width: float) -> str:
    value = str(text or "")
    if stringWidth(value, font, size) <= max_width:
        return value
    while value and stringWidth(f"{value}...", font, size) > max_width:
        value = value[:-1]
    return f"{value}..."


def _frame_path(frame_url: Any) -> Path | None:
    if not isinstance(frame_url, str) or "/assets/" not in frame_url:
        return None
    try:
        return resolve_processed_asset_path(frame_url.split("/assets/", 1)[1])
    except Exception:
        return None


def _clock(seconds: Any) -> str:
    total = max(0, int(float(seconds or 0)))
    minutes, secs = divmod(total, 60)
    return f"{minutes}:{secs:02d}"


def _time_range(start: Any, end: Any) -> str:
    start_label = _clock(start)
    end_label = _clock(end)
    return start_label if start_label == end_label else f"{start_label} - {end_label}"


def _duration_label(seconds: Any) -> str:
    total = int(float(seconds or 0))
    if total <= 0:
        return "Unknown"
    minutes, secs = divmod(total, 60)
    return f"{minutes} min {secs:02d} sec"
